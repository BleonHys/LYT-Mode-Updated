import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const themeDirectory = root;

/** The generated artifact contains no timestamps or machine-specific paths. */
export async function renderTheme() {
  const directory = path.join(themeDirectory, 'src');
  const modules = (await readdir(directory)).filter(name => name.endsWith('.css')).sort();
  if (!modules.length) throw new Error('No CSS source modules found.');
  const sections = await Promise.all(modules.map(async name => {
    const source = (await readFile(path.join(directory, name), 'utf8')).replace(/\r\n/g, '\n').trim();
    return `/* Source: src/${name} */\n${source}\n`;
  }));
  // Obsidian installs only theme.css and manifest.json. Keep complete license
  // notices in the CSS too, so the embedded fonts retain their notices there.
  const notices = await Promise.all(['LICENSE', 'licenses/DM-Sans-OFL.txt', 'licenses/DM-Mono-OFL.txt'].map(async name => (await readFile(path.join(root, name), 'utf8')).replace(/\r\n/g, '\n')));
  const header = [
    'Focus-LYT — generated by npm run build. Edit src/*.css instead.',
    notices[0].trim(),
    'Embedded DM Sans / DM Mono fonts — SIL Open Font License 1.1.',
    "Original embedded DM Sans copyright: Copyright 2014-2017 Indian Type Foundry (info@indiantypefoundry.com) with Reserved Font Name 'Poppins'. Copyright 2019 Google LLC.",
    notices[1].trim(), notices[2].trim()
  ].join('\n\n').replaceAll('*/', '* /');
  return `/*\n${header}\n*/\n\n${sections.join('\n')}`;
}

async function packageTheme() {
  const check = spawnSync(process.execPath, [path.join(root, 'scripts/check.mjs')], { cwd: root, stdio: 'inherit' });
  if (check.status !== 0) throw new Error('Release validation failed.');
  const manifest = JSON.parse(await readFile(path.join(themeDirectory, 'manifest.json'), 'utf8'));
  if (!/^\d+\.\d+\.\d+$/.test(manifest.version)) throw new Error('Release version must be x.y.z.');
  await mkdir(path.join(root, 'dist'), { recursive: true });
  const archive = path.join(root, 'dist', `focus-lyt-${manifest.version}.zip`);
  // Python's standard library keeps release packaging dependency-free and deterministic.
  const python = `import pathlib, sys, zipfile
root = pathlib.Path(sys.argv[1])
files = [(root / name, pathlib.Path('Focus-LYT') / name) for name in ['theme.css', 'manifest.json', 'LICENSE', 'THIRD-PARTY-NOTICES.md']]
files += [(root / 'docs/GUIDE.de.md', pathlib.Path('Focus-LYT/README.md'))]
files += [(p, pathlib.Path('Focus-LYT') / p.relative_to(root)) for p in sorted((root / 'licenses').glob('*.txt'))]
files += [(p, p.relative_to(root)) for p in sorted((root / 'examples').rglob('*.md'))]
files += [(root / 'focus-lyt-controls' / name, pathlib.Path('focus-lyt-controls') / name) for name in ['main.js', 'manifest.json', 'styles.css', 'README.md', 'LICENSE']]
with zipfile.ZipFile(sys.argv[2], 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for source, relative in sorted(files, key=lambda pair: pair[1].as_posix()):
        info = zipfile.ZipInfo(relative.as_posix(), date_time=(2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        content = source.read_bytes()
        if source == root / 'docs/GUIDE.de.md':
            content = content.replace(b'](../LICENSE)', b'](LICENSE)').replace(b'](../THIRD-PARTY-NOTICES.md)', b'](THIRD-PARTY-NOTICES.md)')
        archive.writestr(info, content)
print(sys.argv[2])
`;
  const packaged = spawnSync('python3', ['-c', python, root, archive], { cwd: root, stdio: 'inherit' });
  if (packaged.error) throw packaged.error;
  if (packaged.status !== 0) throw new Error('Could not create release archive.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = await renderTheme();
  await writeFile(path.join(themeDirectory, 'theme.css'), css);
  console.log(`Built theme.css (${Buffer.byteLength(css)} bytes).`);
  if (process.argv.includes('--package')) await packageTheme();
}
